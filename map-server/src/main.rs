//! Map server entry point.
//!
//! The server itself lives in the `map_server` library crate so the engine
//! can also be embedded in-process (see the `content-test` runner). This
//! binary is a thin shim that just runs it.

use anyhow::Result;

#[tokio::main]
async fn main() -> Result<()> {
    map_server::run().await
}
