-- 9-byte {itemId u32 LE, flag byte, price u32 LE} records, aligned in order to a companion
-- (rangeStart,count) index table. No public Meteor lineage previously shipped this table; the
-- server has always had shopRange (slot ranges) but nothing mapping a slot to an item+price,
