-- slots 1051001-1051008: 8/8 items + prices matched exactly
-- -- see the PR description) and cross-checked so every non-empty itemId here exists in
-- gamedata_items. Wired + confirmed working end-to-end (item purchased, gil deducted) against
-- the C# Project Meteor reference server; not yet boot-tested against this Rust port's Lua
-- engine specifically -- see the PR's test-plan notes.
